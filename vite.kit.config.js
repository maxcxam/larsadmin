import { defineConfig } from 'vite'
import vue from '@vitejs/plugin-vue'
import { apiVersion } from './vite.config.js'

// Builds kit/sdk.js (design 1.5 §6.1, §6.4): the `larsadmin` SDK module (resources/js/sdk/index.js) with `vue` and
// `@inertiajs/vue3` external, for extension authors' vitest (the preset aliases `larsadmin` to it). At runtime the
// panel serves the SDK as runtime/larsadmin.js instead. Run by `npm run build` after the panel build; CI checks
// that the committed file is up to date.
export default defineConfig({
    plugins: [vue()],
    define: {
        __LARSADMIN_API_VERSION__: JSON.stringify(apiVersion()),
    },
    build: {
        outDir: 'kit',
        emptyOutDir: false,
        copyPublicDir: false,
        minify: false,
        lib: {
            entry: 'resources/js/sdk/index.js',
            formats: ['es'],
            fileName: () => 'sdk.js',
        },
        rolldownOptions: {
            external: (id) => id === 'vue' || id === '@inertiajs/vue3',
            output: {
                codeSplitting: false,
                banner: '// Generated by `npm run build` (vite.kit.config.js) from resources/js/sdk/index.js. Do not edit.',
            },
        },
    },
})
